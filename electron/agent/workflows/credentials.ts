// ── Run-scoped login credentials ────────────────────────────────────────────
//
// Spec §12. Credentials live in agent-browser's own vault, never in demio:
// the same reasoning that kept `elevenLabsKey` out of the demo-video workflow
// input schema (demo-video.ts:58-64) applies with more force to a user's
// password — `createRun`/`start`/`resume` snapshot `inputData` into a LibSQL
// row on every suspend.
//
// The vault profile is named deterministically from the workspace path, so
// every cleanup site can compute it without being handed anything.
//
// **Known residual risk, deliberately accepted here:** the password still
// transits the conversation, because `ask_user` is the only capture channel
// the harness has and the controller persists messages and tool arguments to
// `mastra_messages`. What this module removes is every OTHER copy — argv, the
// process listing, demio's logs, and agent-browser's action logs — which is
// what `--password-stdin` buys. Closing the last one needs a capture path
// that bypasses the model entirely (a preload-side secret field writing
// straight to the vault); that is a separate change, not this plan.
//
// To be explicit about what that leaves behind: the plaintext password
// persists in `mastra_messages` in `~/.demio/mastra.db` (unencrypted
// SQLite), and none of this module's three deletion sites — success, abort,
// thread deletion — touch that table, nor does deleting the thread's store
// directory. The `elevenLabsKey` precedent cited above was specifically
// about keeping a secret OUT of that database; the password takes the same
// route in anyway, just into a different table (`mastra_messages` rather
// than a workflow input snapshot).

import path from "node:path"
import { execAgentBrowser } from "../../lib/agent-browser/exec"
import { shellQuote } from "../../lib/agent-browser/quote"
import log from "../../lib/logger"

/**
 * `demio-<threadId>`, from the workspace directory name.
 *
 * Sanitised rather than trusted: the name reaches the CLI as an argument, and
 * a thread id is only ever generated by the store — but "only ever" is not a
 * guarantee worth relying on at a shell boundary.
 */
export function vaultProfileName(workspace: string): string {
  const threadId = path.basename(workspace).replace(/[^A-Za-z0-9_-]/g, "")
  if (!threadId) {
    throw new Error(
      `credentials: cannot derive a vault profile name from workspace "${workspace}"`
    )
  }
  return `demio-${threadId}`
}

/**
 * Positive evidence that a login form is on screen.
 *
 * Answers the one question `auth login`'s exit code cannot: did we actually
 * get in? Exit 0 is not proof — observed on workik.com, where `auth login`
 * filled both fields, found no submit control it recognised, and exited 0
 * with the form sitting there unsubmitted.
 *
 * Only ever true on evidence. A probe that cannot run returns false, so an
 * unrelated fault is never reported as an authentication failure.
 */
async function loginFormVisible(): Promise<boolean> {
  const probe = await execAgentBrowser(
    [`eval "!!document.querySelector('input[type=password]')"`],
    { timeout: 10_000 }
  )
  // `output` is `string | Record<string, unknown>` — agent-browser JSON-parses
  // stdout when it can, so `true` arrives as a boolean, not the string "true".
  return probe.ok && /\btrue\b/.test(JSON.stringify(probe.output))
}

/**
 * Does a trusted input event reach the page? False only on evidence: the
 * listener was armed, the pointer moved, and the page never heard it. A mouse
 * MOVE, because a click could press something.
 */
async function tabHearsInput(): Promise<boolean> {
  const arm = await execAgentBrowser(
    [
      `eval "window.__demioInput=0;window.addEventListener('mousemove',()=>{window.__demioInput=1},{capture:true,once:true});1"`,
    ],
    { timeout: 10_000 }
  )
  const move = await execAgentBrowser(["mouse move 7 7"], { timeout: 10_000 })
  if (!arm.ok || !move.ok) return true
  const heard = await execAgentBrowser([`eval "window.__demioInput===1"`], {
    timeout: 10_000,
  })
  return !(heard.ok && /\bfalse\b/.test(JSON.stringify(heard.output)))
}

/**
 * Un-deafen the tab after a sign-in.
 *
 * The first successful sign-in in a fresh Chrome leaves its tab deaf to
 * trusted input: clicks and key presses are acknowledged over CDP and then
 * dropped, while `eval` carries on working. Reproduced with Chrome for Testing
 * 148/151 and Chrome 153 over raw CDP, no agent-browser involved, headed and
 * headless, on any site — a wrong password, a form with no password field and
 * a plain navigation do not do it, so it is Chrome's own reaction to a
 * credential that worked. No launch flag tried prevents it (`--incognito`,
 * `--enable-automation`, Puppeteer's whole default set).
 *
 * A same-site navigation does not clear it. One navigation OFF the site does,
 * and it does not come back in that browser. In a demo the first sign-in is
 * `save_login`'s own test login — so that login verified, and then the
 * rehearsal's `auth login` filled the form and clicked a button that never
 * heard it. One smoke run burned 100 rehearsal steps on that click.
 */
async function reviveTab(): Promise<void> {
  if (await tabHearsInput()) return
  const at = await execAgentBrowser(["get url"], { timeout: 10_000 })
  const landed = typeof at.output === "string" ? at.output.trim() : ""
  await execAgentBrowser(["open about:blank"], { timeout: 20_000 })
  if (/^https?:\/\//.test(landed)) {
    await execAgentBrowser([`open ${shellQuote(landed)}`], { timeout: 30_000 })
  }
  if (await tabHearsInput()) {
    log.info("[credentials] tab was deaf to input after sign-in — revived")
  } else {
    log.warn(
      "[credentials] tab is STILL deaf to input after sign-in: clicks and " +
        "key presses will not reach the page"
    )
  }
}

export async function saveCredentials(opts: {
  workspace: string
  loginUrl: string
  username: string
  password: string
  usernameSelector?: string
  passwordSelector?: string
  submitSelector?: string
}): Promise<{ ok: boolean; detail: string; verified: boolean }> {
  const profile = vaultProfileName(opts.workspace)
  const parts = [
    `auth save ${shellQuote(profile)}`,
    `--url ${shellQuote(opts.loginUrl)}`,
    `--username ${shellQuote(opts.username)}`,
    // NEVER --password: it would land in argv, and therefore in any process
    // listing and in demio's own command logging.
    "--password-stdin",
  ]
  if (opts.usernameSelector)
    parts.push(`--username-selector ${shellQuote(opts.usernameSelector)}`)
  if (opts.passwordSelector)
    parts.push(`--password-selector ${shellQuote(opts.passwordSelector)}`)
  if (opts.submitSelector)
    parts.push(`--submit-selector ${shellQuote(opts.submitSelector)}`)

  const res = await execAgentBrowser([parts.join(" ")], {
    timeout: 20_000,
    stdin: opts.password,
  })
  // `res.error`/`res.output` are safe to surface: `auth save` echoes "✓ Done"
  // and never the password. Verified against the installed binary.
  if (!res.ok) {
    return {
      ok: false,
      verified: false,
      detail: res.error || "auth save failed",
    }
  }

  // Save, then PROVE it. `auth save` only writes a file — it never touches a
  // browser, so on its own it cannot tell whether the stored selectors match
  // the product's login form. That gap is what let a broken login sit
  // undetected: every later `auth login` timed out, and every caller read the
  // timeout as "already signed in".
  //
  // Proving it HERE is what makes it fixable. This runs while the caller still
  // has the login page open and the context to inspect it, so a failure comes
  // back as something the model can act on — read the form's DOM, find the real
  // control, call save_login again — instead of as a scene deviation twenty
  // minutes later with the camera rolling.
  const login = await loginProfile(opts.workspace)
  if (!login.stillOnLoginForm) {
    return {
      ok: true,
      verified: true,
      detail: `saved vault profile ${profile} and verified a test login`,
    }
  }
  return {
    ok: true,
    verified: false,
    detail:
      `saved vault profile ${profile}, but a test login did NOT sign in ` +
      `(${login.detail}) — a password field is still on screen. The stored ` +
      `selectors do not match this login form. Inspect the form and call ` +
      `save_login again with the selectors you read off the page.`,
  }
}

export async function hasProfile(workspace: string): Promise<boolean> {
  const profile = vaultProfileName(workspace)
  const res = await execAgentBrowser([`auth show ${shellQuote(profile)}`], {
    timeout: 10_000,
  })
  return res.ok
}

/**
 * Log in using the saved profile. Camera-off only — never call this with a
 * recording running.
 *
 * `auth login` navigates to the profile's URL and then waits for the username
 * field (`handle_auth_login`, agent-browser `native/actions.rs:8394`). On a
 * session that is ALREADY logged in that URL redirects away, there is no form
 * to wait for, and it times out rather than succeeding — which is why callers
 * historically treated any failure here as advisory.
 *
 * **That conflation hid a total outage.** A wrong `--username-selector`
 * produces the identical timeout, and every caller logged it as "expected
 * when the session is already authenticated" and carried on. The two cases
 * are distinguishable and this function now distinguishes them: after a
 * failure, probe for a visible password field. `auth login` has just
 * navigated to the login URL, so a password field on screen means we are
 * sitting on the login form — not signed in, and the timeout was real.
 *
 * `stillOnLoginForm` is only ever true on positive evidence, and it is probed
 * on EVERY outcome — including exit 0. A zero exit is not proof of a login: on
 * workik.com `auth login` filled both fields, could not match a submit control
 * against its three auto-detect patterns, and exited 0 anyway. Replay read
 * that as success and failed one step later on the assertion instead, with the
 * camera rolling.
 */
export async function loginProfile(
  workspace: string
): Promise<{ ok: boolean; detail: string; stillOnLoginForm: boolean }> {
  const profile = vaultProfileName(workspace)
  const res = await execAgentBrowser([`auth login ${shellQuote(profile)}`], {
    timeout: 45_000,
  })
  const stillOnLoginForm = await loginFormVisible()
  if (res.ok && !stillOnLoginForm) {
    await reviveTab()
    return { ok: true, detail: "logged in", stillOnLoginForm: false }
  }
  return {
    ok: false,
    detail: stillOnLoginForm
      ? res.error ||
        "auth login exited 0 but a password field is still on screen"
      : res.error || "auth login failed",
    stillOnLoginForm,
  }
}

/**
 * Delete the run's vault profile. Idempotent: `auth delete` exits 1 with
 * "not found" when there is nothing to delete, which is a success for our
 * purposes — every caller is a cleanup path that must not throw.
 */
export async function deleteProfile(workspace: string): Promise<void> {
  let profile: string
  try {
    profile = vaultProfileName(workspace)
  } catch {
    return
  }
  try {
    const res = await execAgentBrowser([`auth delete ${shellQuote(profile)}`], {
      timeout: 10_000,
    })
    if (
      !res.ok &&
      !/not found/i.test(`${res.error ?? ""}${res.output ?? ""}`)
    ) {
      log.warn(
        `[credentials] failed to delete vault profile ${profile}: ${res.error}`
      )
    }
  } catch (err) {
    log.warn(
      `[credentials] delete threw for ${profile}: ${
        err instanceof Error ? err.message : String(err)
      }`
    )
  }
}
